import React from 'react'
import { Platform } from 'react-native'

import { render, screen } from 'tests/utils'
import { ModalDetailed } from 'ui/designSystem/ModalDetailed/ModalDetailed'
import { Typo } from 'ui/theme'

const defaultProps = {
  title: 'Detailed modal title',
  description: 'Detailed modal description',
  onClose: jest.fn(),
  primaryButton: {
    wording: 'Confirm',
    accessibilityLabel: 'Confirm action',
    onPress: jest.fn(),
  },
  children: <Typo.Body>Interactive content</Typo.Body>,
}

describe('ModalDetailed', () => {
  it('should display its title, description, content and action', () => {
    render(<ModalDetailed {...defaultProps} />)

    expect(screen.getByText('Detailed modal title')).toBeOnTheScreen()
    expect(screen.getByText('Detailed modal description')).toBeOnTheScreen()
    expect(screen.getByText('Interactive content')).toBeOnTheScreen()
    expect(screen.getByText('Confirm')).toBeOnTheScreen()
  })

  it('should only display the loader content in loading mode', () => {
    render(
      <ModalDetailed
        title="Loading modal"
        onClose={jest.fn()}
        isLoading
        loadingMessage="Loading information"
      />
    )

    expect(screen.getByText('Loading modal')).toBeOnTheScreen()
    expect(screen.getByText('Loading information')).toBeOnTheScreen()
    expect(screen.queryByText('Interactive content')).not.toBeOnTheScreen()
    expect(screen.queryByText('Confirm')).not.toBeOnTheScreen()
  })

  it('should provide the available sheet height when footer is fixed', () => {
    Platform.OS = 'ios'

    render(<ModalDetailed {...defaultProps} isFooterFixed />)

    const modalWrapperStyle = screen.getByTestId('modalDetailedWrapper').props.style

    expect(modalWrapperStyle.height).toEqual(1318)
    expect(modalWrapperStyle.maxHeight).toEqual(1318)
  })

  describe('maxHeight calculation based on platform', () => {
    const originalPlatform = Platform.OS

    afterEach(() => {
      Platform.OS = originalPlatform
    })

    it('should subtract safe area insets on iOS', () => {
      Platform.OS = 'ios'

      render(<ModalDetailed {...defaultProps} />)

      expect(screen.getByTestId('modalDetailedWrapper').props.style.maxHeight).toEqual(1302)
    })

    it('should use the full window height on Android', () => {
      Platform.OS = 'android'

      render(<ModalDetailed {...defaultProps} />)

      expect(screen.getByTestId('modalDetailedWrapper').props.style.maxHeight).toEqual(1334)
    })
  })
})
