import React from 'react'

import { render, screen, within } from 'tests/utils/web'
import { ModalDetailed } from 'ui/designSystem/ModalDetailed/ModalDetailed'
import { Typo } from 'ui/theme'

describe('ModalDetailed on web', () => {
  it('should expose its title through the dialog accessible name', () => {
    render(
      <ModalDetailed
        title="Detailed modal title"
        onClose={jest.fn()}
        primaryButton={{
          wording: 'Confirm',
          accessibilityLabel: 'Confirm action',
          onPress: jest.fn(),
        }}>
        <Typo.Body>Interactive content</Typo.Body>
      </ModalDetailed>
    )

    expect(screen.getByRole('dialog', { name: 'Detailed modal title' })).toBeInTheDocument()
  })

  it('should render an action as a link when it has an href', () => {
    render(
      <ModalDetailed
        title="Detailed modal title"
        onClose={jest.fn()}
        primaryButton={{
          wording: 'Read more',
          accessibilityLabel: 'Read more about this subject',
          href: '/more-information',
          onPress: jest.fn(),
        }}>
        <Typo.Body>Interactive content</Typo.Body>
      </ModalDetailed>
    )

    expect(screen.getByRole('link', { name: 'Read more about this subject' })).toHaveAttribute(
      'href',
      '/more-information'
    )
  })

  it('should expose close then back as the first interactive elements in DOM order', () => {
    render(
      <ModalDetailed
        title="Detailed modal title"
        onClose={jest.fn()}
        onGoBack={jest.fn()}
        primaryButton={{
          wording: 'Confirm',
          accessibilityLabel: 'Confirm action',
          onPress: jest.fn(),
        }}>
        <Typo.Body>Interactive content</Typo.Body>
      </ModalDetailed>
    )

    const dialogButtons = within(
      screen.getByRole('dialog', { name: 'Detailed modal title' })
    ).getAllByRole('button')

    expect(dialogButtons[0]).toHaveAccessibleName('Quitter')
    expect(dialogButtons[1]).toHaveAccessibleName('Retourner à l’étape précédente')
  })

  it('should make the scrollable content keyboard accessible', () => {
    render(
      <ModalDetailed
        title="Detailed modal title"
        onClose={jest.fn()}
        isFooterFixed
        primaryButton={{
          wording: 'Confirm',
          accessibilityLabel: 'Confirm action',
          onPress: jest.fn(),
        }}>
        <Typo.Body>Scrollable content without an interactive element</Typo.Body>
      </ModalDetailed>
    )

    expect(screen.getByTestId('modalDetailedScrollView')).toHaveAttribute('tabindex', '0')
  })
})
