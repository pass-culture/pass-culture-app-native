import React from 'react'

import { render, screen, userEvent } from 'tests/utils'
import { ModalDetailedHeader } from 'ui/designSystem/ModalDetailed/ModalDetailedHeader'

const user = userEvent.setup()

jest.useFakeTimers()

describe('ModalDetailedHeader', () => {
  it('should display the title, close button and optional back button', () => {
    render(
      <ModalDetailedHeader
        title="Modal title"
        titleId="modal-title"
        onClose={jest.fn()}
        onGoBack={jest.fn()}
      />
    )

    expect(screen.getByText('Modal title')).toBeOnTheScreen()
    expect(screen.getByLabelText('Quitter')).toBeOnTheScreen()
    expect(screen.getByLabelText('Retourner à l’étape précédente')).toBeOnTheScreen()
  })

  it('should call close and back actions', async () => {
    const onClose = jest.fn()
    const onGoBack = jest.fn()

    render(
      <ModalDetailedHeader
        title="Modal title"
        titleId="modal-title"
        onClose={onClose}
        onGoBack={onGoBack}
      />
    )

    await user.press(screen.getByLabelText('Quitter'))
    await user.press(screen.getByLabelText('Retourner à l’étape précédente'))

    expect(onClose).toHaveBeenCalledTimes(1)
    expect(onGoBack).toHaveBeenCalledTimes(1)
  })

  it('should not display the back button when no action is provided', () => {
    render(<ModalDetailedHeader title="Modal title" titleId="modal-title" onClose={jest.fn()} />)

    expect(screen.queryByLabelText('Retourner à l’étape précédente')).not.toBeOnTheScreen()
  })
})
