import { FunctionComponent, ReactNode } from 'react'

import { AccessibleIcon } from 'ui/svg/icons/types'

type ModalButtonProps = {
  wording: string
  accessibilityLabel: string
  accessibilityHint?: string
  icon?: FunctionComponent<AccessibleIcon>
  iconPosition?: 'left' | 'right'
  disabled?: boolean
  isLoading?: boolean
  type?: 'button' | 'submit' | 'reset'
  target?: string
  onPress: () => void
  href?: string
}

export type ModalDetailedFooterProps = {
  buttonsDescription?: string
  primaryButton?: ModalButtonProps
  secondaryButton?: ModalButtonProps
  tertiaryButton?: ModalButtonProps
}

export type ModalDetailedHeaderProps = {
  title: string
  titleId: string
  onClose: () => void
  onGoBack?: () => void
  closeAccessibilityLabel?: string
  backAccessibilityLabel?: string
}

type ModalDetailedBaseProps = Omit<ModalDetailedHeaderProps, 'titleId'> & {
  description?: string
}

type ModalDetailedWithContentProps = ModalDetailedBaseProps &
  ModalDetailedFooterProps & {
    isLoading?: false
    loadingMessage?: never
    children: ReactNode
    isFooterFixed?: boolean
  } & (
    | { primaryButton: ModalButtonProps }
    | { secondaryButton: ModalButtonProps }
    | { tertiaryButton: ModalButtonProps }
  )

type ModalDetailedLoadingProps = Omit<ModalDetailedBaseProps, 'description'> & {
  isLoading: true
  loadingMessage: string
  description?: never
  children?: never
  isFooterFixed?: never
  buttonsDescription?: never
  primaryButton?: never
  secondaryButton?: never
  tertiaryButton?: never
}

export type ModalDetailedProps = ModalDetailedWithContentProps | ModalDetailedLoadingProps

export type ModalDetailedLayoutProps = ModalDetailedProps & {
  titleId: string
}
