import React from 'react'

import { render, screen, userEvent } from 'tests/utils'
import { ModalDetailedFooter } from 'ui/designSystem/ModalDetailed/ModalDetailedFooter'

const user = userEvent.setup()

jest.useFakeTimers()

const primaryButton = {
  wording: 'Primary action',
  accessibilityLabel: 'Primary action label',
  onPress: jest.fn(),
}
const secondaryButton = {
  wording: 'Secondary action',
  accessibilityLabel: 'Secondary action label',
  onPress: jest.fn(),
}
const tertiaryButton = {
  wording: 'Tertiary action',
  accessibilityLabel: 'Tertiary action label',
  onPress: jest.fn(),
}

describe('ModalDetailedFooter', () => {
  it('should render actions in primary to tertiary order on mobile', () => {
    render(
      <ModalDetailedFooter
        primaryButton={primaryButton}
        secondaryButton={secondaryButton}
        tertiaryButton={tertiaryButton}
      />
    )

    const actions = screen.getAllByText(/action$/i)

    expect(actions[0]).toHaveTextContent('Primary action')
    expect(actions[1]).toHaveTextContent('Secondary action')
    expect(actions[2]).toHaveTextContent('Tertiary action')
  })

  it('should render actions in tertiary to primary order on desktop', () => {
    render(
      <ModalDetailedFooter
        primaryButton={primaryButton}
        secondaryButton={secondaryButton}
        tertiaryButton={tertiaryButton}
      />,
      { theme: { isDesktopViewport: true } }
    )

    const actions = screen.getAllByText(/action$/i)

    expect(actions[0]).toHaveTextContent('Tertiary action')
    expect(actions[1]).toHaveTextContent('Secondary action')
    expect(actions[2]).toHaveTextContent('Primary action')
  })

  it('should render actions in tertiary to primary order on tablet', () => {
    render(
      <ModalDetailedFooter
        primaryButton={primaryButton}
        secondaryButton={secondaryButton}
        tertiaryButton={tertiaryButton}
      />,
      { theme: { isTabletViewport: true, isMobileViewport: false } }
    )

    const actions = screen.getAllByText(/action$/i)

    expect(actions[0]).toHaveTextContent('Tertiary action')
    expect(actions[1]).toHaveTextContent('Secondary action')
    expect(actions[2]).toHaveTextContent('Primary action')
  })

  it('should display the optional buttons description', () => {
    render(
      <ModalDetailedFooter
        primaryButton={primaryButton}
        buttonsDescription="Information about the actions"
      />
    )

    expect(screen.getByText('Information about the actions')).toBeOnTheScreen()
  })

  it('should call the selected action', async () => {
    render(<ModalDetailedFooter primaryButton={primaryButton} />)

    await user.press(screen.getByText('Primary action'))

    expect(primaryButton.onPress).toHaveBeenCalledTimes(1)
  })
})
