import React, { FunctionComponent } from 'react'
import { Platform, useWindowDimensions } from 'react-native'
import { useSafeAreaInsets } from 'react-native-safe-area-context'
import styled from 'styled-components/native'
import { v4 as uuidv4 } from 'uuid'

import { MODAL_DETAILED_DESKTOP_MAX_WIDTH } from 'ui/designSystem/ModalDetailed/constants'
import { ModalDetailedLayout } from 'ui/designSystem/ModalDetailed/ModalDetailedLayout'
import { ModalDetailedProps } from 'ui/designSystem/ModalDetailed/types'

export const ModalDetailed: FunctionComponent<ModalDetailedProps> = (props) => {
  const { top, bottom } = useSafeAreaInsets()
  const { height } = useWindowDimensions()
  const titleId = uuidv4()

  // Keep the same maximum height as ModalSimple for content-sized modals.
  // A fixed-footer form sheet starts below the top safe area, while its bottom
  // already reaches the visible sheet boundary. Only remove the top inset.
  const iOSHeight = height - top - bottom
  const isFooterFixed = !props.isLoading && !!props.isFooterFixed
  const contentMaxHeight = Platform.OS === 'android' ? height : iOSHeight
  const fixedFooterHeight = Platform.OS === 'android' ? height : height - top
  const modalHeight = isFooterFixed ? fixedFooterHeight : undefined
  const maxHeight = isFooterFixed ? fixedFooterHeight : contentMaxHeight

  return (
    <ModalWrapper
      accessibilityViewIsModal
      accessibilityLabel={props.title}
      maxHeight={maxHeight}
      height={modalHeight}
      testID="modalDetailedWrapper">
      <ModalDetailedLayout {...props} titleId={titleId} />
    </ModalWrapper>
  )
}

const ModalWrapper = styled.View<{ maxHeight: number; height?: number }>(
  ({ maxHeight, height }) => ({
    height,
    maxHeight,
    maxWidth: MODAL_DETAILED_DESKTOP_MAX_WIDTH,
    width: '100%',
    alignSelf: 'center',
    overflow: 'hidden',
  })
)
