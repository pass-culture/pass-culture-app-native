import React, { ComponentProps, useState } from 'react'
import { TextInput } from 'react-native'

import {
  checkAccessibilityFor,
  fireEvent,
  render,
  screen,
  userEvent,
  within,
} from 'tests/utils/web'

import { RadioButtonGroup } from './RadioButtonGroup'

const options = [
  { key: 'first', label: 'First' },
  { key: 'second', label: 'Second', description: 'Description' },
  { key: 'third', label: 'Third' },
]
const onChange = jest.fn()
type Props = ComponentProps<typeof RadioButtonGroup>

const ControlledGroup = ({ value = '', ...props }: Partial<Props>) => {
  const [selection, setSelection] = useState(value)
  return (
    <React.Fragment>
      <button aria-label="Before" />
      <RadioButtonGroup
        label="Choices"
        options={options}
        {...props}
        value={selection}
        onChange={(next) => {
          onChange(next)
          setSelection(next)
        }}
      />
      <button aria-label="After" />
    </React.Fragment>
  )
}

describe.each(['default', 'detailed'] as const)('RadioButtonGroup %s on web', (variant) => {
  it('exposes a named group and radio states without repeating their state in the name', async () => {
    const { container } = render(<ControlledGroup variant={variant} value="Second" />)

    const group = screen.getByRole('radiogroup', { name: 'Choices' })

    expect(within(group).getByRole('radio', { name: 'Second - Description' })).toBeChecked()
    expect(within(group).getByRole('radio', { name: 'First' })).not.toBeChecked()
    expect(await checkAccessibilityFor(container)).toHaveNoViolations()
  })

  it('enters on the selection and leaves with a single Tab in either direction', async () => {
    const user = await userEvent.setup()
    render(<ControlledGroup variant={variant} value="Second" />)

    await user.tab()

    expect(screen.getByRole('button', { name: 'Before' })).toHaveFocus()

    await user.tab()

    expect(screen.getByRole('radio', { name: 'Second - Description' })).toHaveFocus()

    await user.tab()

    expect(screen.getByRole('button', { name: 'After' })).toHaveFocus()

    await user.tab({ shift: true })

    expect(screen.getByRole('radio', { name: 'Second - Description' })).toHaveFocus()

    await user.tab({ shift: true })

    expect(screen.getByRole('button', { name: 'Before' })).toHaveFocus()
  })

  it.each([
    ['ArrowRight', 'Second - Description'],
    ['ArrowDown', 'Second - Description'],
    ['ArrowLeft', 'Third'],
    ['ArrowUp', 'Third'],
  ])('moves and selects with %s, including wrapping', async (key, name) => {
    const user = await userEvent.setup()
    render(<ControlledGroup variant={variant} value="First" />)
    await user.tab()
    await user.tab()

    await user.keyboard(`[${key}]`)

    expect(screen.getByRole('radio', { name })).toHaveFocus()
    expect(screen.getByRole('radio', { name })).toBeChecked()
    expect(screen.getAllByRole('radio', { checked: true })).toHaveLength(1)
    expect(onChange).toHaveBeenCalledTimes(1)
  })

  it('selects with Space and does not deselect with Space or click', async () => {
    const user = await userEvent.setup()
    render(<ControlledGroup variant={variant} />)
    await user.tab()
    await user.tab()
    const first = screen.getByRole('radio', { name: 'First' })

    expect(first).toHaveFocus()
    expect(first).not.toBeChecked()

    await user.keyboard('[Space][Space]')
    await user.click(first)

    expect(first).toBeChecked()
    expect(onChange).toHaveBeenCalledTimes(1)
  })

  it('skips disabled options for entry and arrow navigation', async () => {
    const user = await userEvent.setup()
    render(
      <ControlledGroup
        variant={variant}
        value="Second"
        options={options.map((option) => ({ ...option, disabled: option.key === 'second' }))}
      />
    )
    await user.tab()
    await user.tab()

    expect(screen.getByRole('radio', { name: 'First' })).toHaveFocus()

    await user.keyboard('[ArrowRight]')

    expect(screen.getByRole('radio', { name: 'Third' })).toHaveFocus()

    fireEvent.click(screen.getByRole('radio', { name: 'Second - Description' }))

    expect(screen.getByRole('radio', { name: 'Third' })).toBeChecked()
    expect(screen.getByRole('radio', { name: 'Second - Description' })).toHaveAttribute(
      'aria-disabled',
      'true'
    )
  })

  it.each([
    { unavailableOptions: [] },
    { unavailableOptions: options.map((option) => ({ ...option, disabled: true })) },
  ])('has no tab stop when no option is available', async ({ unavailableOptions }) => {
    const user = await userEvent.setup()
    render(<ControlledGroup variant={variant} options={unavailableOptions} />)
    await user.tab()
    await user.tab()

    expect(screen.getByRole('button', { name: 'After' })).toHaveFocus()
  })

  it('disables the entire group even if an option declares disabled=false', async () => {
    const user = await userEvent.setup()
    render(
      <ControlledGroup
        variant={variant}
        disabled
        options={options.map((option) => ({ ...option, disabled: false }))}
      />
    )
    await user.tab()
    await user.tab()

    expect(screen.getByRole('button', { name: 'After' })).toHaveFocus()

    fireEvent.click(screen.getByRole('radio', { name: 'First' }))

    expect(onChange).not.toHaveBeenCalled()
  })

  it('supports a single option without clearing the selection', async () => {
    const user = await userEvent.setup()
    render(<ControlledGroup variant={variant} options={[{ key: 'solo', label: 'Solo' }]} />)
    await user.tab()
    await user.tab()
    await user.keyboard('[ArrowRight][ArrowLeft][ArrowUp][ArrowDown][Space]')

    expect(screen.getByRole('radio', { name: 'Solo' })).toHaveFocus()
    expect(screen.getByRole('radio', { name: 'Solo' })).toBeChecked()
    expect(onChange).toHaveBeenCalledTimes(1)
  })
})

describe('RadioButtonGroup integration', () => {
  it('keeps focus independent from a selection awaiting acceptance', async () => {
    const user = await userEvent.setup()
    const { rerender } = render(
      <RadioButtonGroup label="Choices" options={options} value="First" onChange={onChange} />
    )
    await user.tab()
    await user.keyboard('[ArrowRight]')

    expect(screen.getByRole('radio', { name: 'Second - Description' })).toHaveFocus()
    expect(screen.getByRole('radio', { name: 'First' })).toBeChecked()

    await user.keyboard('[ArrowRight]')

    expect(onChange).toHaveBeenLastCalledWith('Third')
    expect(screen.getByRole('radio', { name: 'Third' })).toHaveFocus()

    rerender(
      <RadioButtonGroup label="Choices" options={options} value="Third" onChange={onChange} />
    )

    expect(screen.getByRole('radio', { name: 'Third' })).toBeChecked()
    expect(screen.getByRole('radio', { name: 'Third' })).toHaveFocus()
  })

  it('resets entry to the actual selection when a pending choice was rejected', async () => {
    const user = await userEvent.setup()
    render(
      <React.Fragment>
        <RadioButtonGroup label="Choices" options={options} value="First" onChange={onChange} />
        <button aria-label="After" />
      </React.Fragment>
    )
    await user.tab()
    await user.keyboard('[ArrowRight]')
    await user.tab()

    expect(screen.getByRole('button', { name: 'After' })).toHaveFocus()

    await user.tab({ shift: true })

    expect(screen.getByRole('radio', { name: 'First' })).toHaveFocus()
  })

  it('updates the entry when options and the controlled value change', async () => {
    const user = await userEvent.setup()
    const { rerender } = render(
      <RadioButtonGroup label="Choices" options={options} value="Second" onChange={onChange} />
    )
    rerender(
      <RadioButtonGroup
        label="Choices"
        options={[{ key: 'new', label: 'New' }, ...options.slice(0, 1)]}
        value="Second"
        onChange={onChange}
      />
    )
    await user.tab()

    expect(screen.getByRole('radio', { name: 'New' })).toHaveFocus()
  })

  it('keeps separate groups independently named and navigable', async () => {
    const user = await userEvent.setup()
    render(
      <React.Fragment>
        <RadioButtonGroup label="First group" options={options} value="" onChange={onChange} />
        <RadioButtonGroup label="Second group" options={options} value="" onChange={onChange} />
      </React.Fragment>
    )
    await user.tab()
    await user.keyboard('[ArrowLeft]')

    expect(
      within(screen.getByRole('radiogroup', { name: 'First group' })).getByRole('radio', {
        name: 'Third',
      })
    ).toHaveFocus()

    await user.tab()

    expect(
      within(screen.getByRole('radiogroup', { name: 'Second group' })).getByRole('radio', {
        name: 'First',
      })
    ).toHaveFocus()
  })

  it('leaves collapsed inputs and nested groups in control of their arrow keys', async () => {
    const user = await userEvent.setup()
    render(
      <ControlledGroup
        variant="detailed"
        value="First"
        options={[
          {
            key: 'first',
            label: 'First',
            collapsed: (
              <React.Fragment>
                <TextInput accessibilityLabel="Address" />
                <RadioButtonGroup label="Nested" options={options} value="" onChange={onChange} />
              </React.Fragment>
            ),
          },
          { key: 'other', label: 'Other' },
        ]}
      />
    )
    await user.tab()
    await user.tab()
    await user.tab()

    expect(screen.getByRole('textbox', { name: 'Address' })).toHaveFocus()

    await user.keyboard('[ArrowRight][ArrowDown]')

    expect(onChange).not.toHaveBeenCalled()

    await user.tab()
    await user.keyboard('[ArrowRight]')

    expect(onChange).toHaveBeenCalledTimes(1)
    expect(onChange).toHaveBeenCalledWith('Second')
    expect(
      within(screen.getByRole('radiogroup', { name: 'Nested' })).getByRole('radio', {
        name: 'Second - Description',
      })
    ).toHaveFocus()
  })

  it('supports the FlatList rendering path and preserves its footer', async () => {
    const user = await userEvent.setup()
    render(
      <ControlledGroup flatListProps={{ ListFooterComponent: <button aria-label="More" /> }} />
    )
    await user.tab()
    await user.tab()
    await user.keyboard('[ArrowUp]')

    expect(screen.getByRole('radio', { name: 'Third' })).toHaveFocus()
    expect(screen.getByRole('radio', { name: 'Third' })).toBeChecked()

    await user.tab()

    expect(screen.getByRole('button', { name: 'More' })).toHaveFocus()
  })

  it('uses the new external selection when entering from outside', async () => {
    const user = await userEvent.setup()
    const { rerender } = render(
      <RadioButtonGroup label="Choices" options={options} value="First" onChange={onChange} />
    )
    rerender(
      <RadioButtonGroup label="Choices" options={options} value="Third" onChange={onChange} />
    )
    await user.tab()

    expect(screen.getByRole('radio', { name: 'Third' })).toHaveFocus()
  })
})
