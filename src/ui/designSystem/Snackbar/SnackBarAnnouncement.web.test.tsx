import React from 'react'

import { act, cleanup, render, screen } from 'tests/utils/web'

import { SnackBarAnnouncement } from './SnackBarAnnouncement.web'
import { SnackBarAnnouncementItem } from './types'

const ANNOUNCEMENT_DURATION = 1000
const ANNOUNCEMENT_GAP = 100

/**
 * The tests/utils/web helper automatically mounts a SnackBarWrapper which renders its own SnackBarAnnouncement.
 * We retrieve the second instance, corresponding to the component explicitly rendered by the test.
 */
const getAnnouncementRegions = () => ({
  status: screen.getAllByRole('status')[1],
  alert: screen.getAllByRole('alert')[1],
})

describe('SnackBarAnnouncement', () => {
  beforeEach(() => {
    jest.useFakeTimers()
  })

  afterEach(() => {
    cleanup()
    jest.clearAllTimers()
    jest.useRealTimers()
  })

  it('should render empty live regions when there are no snackbars', () => {
    render(<SnackBarAnnouncement snackbars={[]} />)

    const { status, alert } = getAnnouncementRegions()

    expect(status).toBeEmptyDOMElement()
    expect(alert).toBeEmptyDOMElement()
  })

  it('should announce a success snackbar in the status live region', () => {
    const snackbars: SnackBarAnnouncementItem[] = [
      { id: '1', label: 'Opération réussie', type: 'success' },
    ]

    render(<SnackBarAnnouncement snackbars={snackbars} />)

    const { status, alert } = getAnnouncementRegions()

    expect(status).toHaveTextContent('Opération réussie')
    expect(alert).toBeEmptyDOMElement()
  })

  it('should announce an error snackbar in the alert live region', () => {
    const snackbars: SnackBarAnnouncementItem[] = [
      { id: '1', label: 'Une erreur est survenue', type: 'error' },
    ]

    render(<SnackBarAnnouncement snackbars={snackbars} />)

    const { status, alert } = getAnnouncementRegions()

    expect(alert).toHaveTextContent('Une erreur est survenue')
    expect(status).toBeEmptyDOMElement()
  })

  it('should announce multiple snackbars sequentially', () => {
    const snackbars: SnackBarAnnouncementItem[] = [
      { id: '1', label: 'Premier message', type: 'success' },
      { id: '2', label: 'Deuxième message', type: 'error' },
    ]

    render(<SnackBarAnnouncement snackbars={snackbars} />)

    const { status, alert } = getAnnouncementRegions()

    expect(status).toHaveTextContent('Premier message')
    expect(alert).toBeEmptyDOMElement()

    act(() => jest.advanceTimersByTime(ANNOUNCEMENT_DURATION))

    expect(status).toBeEmptyDOMElement()

    act(() => jest.advanceTimersByTime(ANNOUNCEMENT_GAP))

    expect(alert).toHaveTextContent('Deuxième message')
  })

  it('should clear pending timeout when unmounted', () => {
    const snackbars: SnackBarAnnouncementItem[] = [
      { id: '1', label: 'Opération réussie', type: 'success' },
    ]

    const initialTimerCount = jest.getTimerCount()
    const { unmount } = render(<SnackBarAnnouncement snackbars={snackbars} />)

    expect(jest.getTimerCount()).toBe(initialTimerCount + 1)

    unmount()

    expect(jest.getTimerCount()).toBe(initialTimerCount)
  })
})
