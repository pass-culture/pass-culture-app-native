import React, { FC, useCallback, useEffect, useRef, useState } from 'react'
import styled from 'styled-components'

import { AccessibilityRole } from 'libs/accessibilityRole/accessibilityRole'

import { SnackBarAnnouncementItem } from './types'

type Props = { snackbars: SnackBarAnnouncementItem[] }
type Announcement = { label: string; type: 'success' | 'error' }

const ANNOUNCEMENT_DURATION = 1000
const ANNOUNCEMENT_GAP = 100

export const SnackBarAnnouncement: FC<Props> = ({ snackbars }) => {
  const announcedIds = useRef(new Set<string>())
  const pendingAnnouncements = useRef<Announcement[]>([])
  const isProcessing = useRef(false)
  const timeoutRef = useRef<ReturnType<typeof setTimeout> | undefined>(undefined)

  const [announcement, setAnnouncement] = useState<Announcement | null>(null)

  const processNextAnnouncement = useCallback(function processNext() {
    const nextAnnouncement = pendingAnnouncements.current.shift()

    if (!nextAnnouncement) {
      isProcessing.current = false
      return
    }

    isProcessing.current = true
    setAnnouncement(nextAnnouncement)

    timeoutRef.current = setTimeout(() => {
      setAnnouncement(null)
      timeoutRef.current = setTimeout(() => processNext(), ANNOUNCEMENT_GAP)
    }, ANNOUNCEMENT_DURATION)
  }, [])

  useEffect(
    function enqueueNewSnackbars() {
      const newSnackbars = snackbars.filter(({ id }) => {
        if (announcedIds.current.has(id)) return false
        announcedIds.current.add(id)
        return true
      })

      pendingAnnouncements.current.push(...newSnackbars.map(({ label, type }) => ({ label, type })))

      if (!isProcessing.current) processNextAnnouncement()
    },
    [snackbars, processNextAnnouncement]
  )

  useEffect(function clearAnnouncementTimeout() {
    return () => {
      if (timeoutRef.current) clearTimeout(timeoutRef.current)
    }
  }, [])

  return (
    <LiveRegionsContainer>
      <LiveRegion role={AccessibilityRole.STATUS} aria-live="polite" aria-atomic="true">
        {announcement?.type === 'success' ? announcement.label : ''}
      </LiveRegion>
      <LiveRegion role={AccessibilityRole.ALERT} aria-live="assertive" aria-atomic="true">
        {announcement?.type === 'error' ? announcement.label : ''}
      </LiveRegion>
    </LiveRegionsContainer>
  )
}

const LiveRegionsContainer = styled.div(() => ({
  position: 'absolute',
  width: 1,
  height: 1,
  overflow: 'hidden',
}))

// Visually hides the live regions while keeping them accessible to screen readers.
// Do not use `display: none`, as it removes elements from the accessibility tree and prevents screen readers from announcing their content.
const LiveRegion = styled.div(() => ({
  position: 'absolute',
  width: 1,
  height: 1,
  padding: 0,
  margin: -1,
  overflow: 'hidden',
  clipPath: 'inset(50%)',
  whiteSpace: 'nowrap',
  border: 0,
}))
