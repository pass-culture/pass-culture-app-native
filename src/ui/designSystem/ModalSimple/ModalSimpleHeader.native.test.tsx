import React from 'react'

import { render, screen, userEvent } from 'tests/utils'
import { ModalSimpleHeader } from 'ui/designSystem/ModalSimple/ModalSimpleHeader'

const mockOnClose = jest.fn()

const user = userEvent.setup()

jest.useFakeTimers()

describe('ModalSimpleHeader', () => {
  it('should render the close button with correct accessibility label', () => {
    render(<ModalSimpleHeader onClose={mockOnClose} />)

    expect(screen.getByLabelText('Fermer la fenêtre')).toBeOnTheScreen()
  })

  it('should call onClose when close button is pressed', async () => {
    render(<ModalSimpleHeader onClose={mockOnClose} />)

    await user.press(screen.getByLabelText('Fermer la fenêtre'))

    expect(mockOnClose).toHaveBeenCalledTimes(1)
  })
})
