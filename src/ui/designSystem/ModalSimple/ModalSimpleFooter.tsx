import React, { FunctionComponent } from 'react'
import { Platform } from 'react-native'
import styled, { useTheme } from 'styled-components/native'

import { ViewGap } from 'ui/components/ViewGap/ViewGap'
import { Button } from 'ui/designSystem/Button/Button'
import { ModalSimpleFooterProps } from 'ui/designSystem/ModalSimple/types'

export const ModalSimpleFooter: FunctionComponent<ModalSimpleFooterProps> = ({
  primaryButton,
  secondaryButton,
  tertiaryButton,
}) => {
  const { isDesktopViewport, isTabletViewport } = useTheme()

  const buttons = [
    primaryButton ? (
      <Button
        {...primaryButton}
        key="primary"
        variant="primary"
        color="brand"
        fullWidth={!isDesktopViewport}
      />
    ) : null,
    secondaryButton ? (
      <Button
        {...secondaryButton}
        key="secondary"
        variant="secondary"
        color="neutral"
        fullWidth={!isDesktopViewport}
      />
    ) : null,
    tertiaryButton ? (
      <Button
        {...tertiaryButton}
        key="tertiary"
        variant="tertiary"
        color="neutral"
        fullWidth={!isDesktopViewport}
      />
    ) : null,
  ].filter(Boolean)

  if (buttons.length === 0) return null

  const orderedButtons = isDesktopViewport || isTabletViewport ? [...buttons].reverse() : buttons

  return <FooterContainer gap={4}>{orderedButtons}</FooterContainer>
}

const FooterContainer = styled(ViewGap)(({ theme }) => ({
  flexShrink: 0,
  flexDirection: theme.isDesktopViewport || theme.isTabletViewport ? 'row' : 'column',
  justifyContent: 'center',
  alignItems: 'center',
  width: '100%',
  paddingHorizontal: theme.designSystem.size.spacing.xxl,
  paddingBottom: Platform.OS === 'ios' ? undefined : theme.designSystem.size.spacing.xxl,
  paddingTop: theme.designSystem.size.spacing.xl,
}))
