import React from 'react'

import { render, screen, userEvent } from 'tests/utils'
import { ModalSimpleFooter } from 'ui/designSystem/ModalSimple/ModalSimpleFooter'

const user = userEvent.setup()

jest.useFakeTimers()

describe('ModalSimpleFooter', () => {
  const mockPrimaryButton = {
    wording: 'Primary Action',
    accessibilityLabel: 'Primary Action Label',
    onPress: jest.fn(),
  }

  const mockSecondaryButton = {
    wording: 'Secondary Action',
    accessibilityLabel: 'Secondary Action Label',
    onPress: jest.fn(),
  }

  const mockTertiaryButton = {
    wording: 'Tertiary Action',
    accessibilityLabel: 'Tertiary Action Label',
    onPress: jest.fn(),
  }

  it('should render nothing when no buttons are provided', () => {
    render(<ModalSimpleFooter />)

    expect(screen.toJSON()).toBeNull()
  })

  it('should render primary, secondary, and tertiary buttons when provided', () => {
    render(
      <ModalSimpleFooter
        primaryButton={mockPrimaryButton}
        secondaryButton={mockSecondaryButton}
        tertiaryButton={mockTertiaryButton}
      />
    )

    expect(screen.getByText('Primary Action')).toBeOnTheScreen()
    expect(screen.getByText('Secondary Action')).toBeOnTheScreen()
    expect(screen.getByText('Tertiary Action')).toBeOnTheScreen()
  })

  it('should call onPress when primary button is pressed', async () => {
    render(<ModalSimpleFooter primaryButton={mockPrimaryButton} />)

    await user.press(screen.getByText('Primary Action'))

    expect(mockPrimaryButton.onPress).toHaveBeenCalledTimes(1)
  })

  it('should call onPress when secondary button is pressed', async () => {
    render(<ModalSimpleFooter secondaryButton={mockSecondaryButton} />)

    await user.press(screen.getByText('Secondary Action'))

    expect(mockSecondaryButton.onPress).toHaveBeenCalledTimes(1)
  })

  it('should call onPress when tertiary button is pressed', async () => {
    render(<ModalSimpleFooter tertiaryButton={mockTertiaryButton} />)

    await user.press(screen.getByText('Tertiary Action'))

    expect(mockTertiaryButton.onPress).toHaveBeenCalledTimes(1)
  })

  it('should render buttons in standard order on mobile viewport', () => {
    render(
      <ModalSimpleFooter primaryButton={mockPrimaryButton} secondaryButton={mockSecondaryButton} />
    )

    const buttons = screen.getAllByText(/Action/)

    expect(buttons[0]).toHaveTextContent('Primary Action')
    expect(buttons[1]).toHaveTextContent('Secondary Action')
  })

  it('should reverse button order on desktop viewport', () => {
    render(
      <ModalSimpleFooter primaryButton={mockPrimaryButton} secondaryButton={mockSecondaryButton} />,
      { theme: { isDesktopViewport: true } }
    )

    const buttons = screen.getAllByText(/Action/)

    expect(buttons[0]).toHaveTextContent('Secondary Action')
    expect(buttons[1]).toHaveTextContent('Primary Action')
  })
})
