import React from 'react'
import { Platform } from 'react-native'

import { remoteIllustrationUrls } from 'shared/illustrations/remoteIllustrations'
import { render, screen } from 'tests/utils'
import { RemoteIllustrationProps } from 'ui/components/RemoteIllustration'
import { ModalSimple } from 'ui/designSystem/ModalSimple/ModalSimple'

const mockOnClose = jest.fn()
const mockPrimaryButton = {
  wording: 'Confirm',
  accessibilityLabel: 'Confirm action',
  onPress: jest.fn(),
}
const mockSecondaryButton = {
  wording: 'Cancel',
  accessibilityLabel: 'Cancel action',
  onPress: jest.fn(),
}
const mockIllustration: RemoteIllustrationProps = {
  backgroundColor: 'positive02',
  url: remoteIllustrationUrls.validStampMosaïcLarge,
}

const defaultProps = {
  title: 'Modal Title',
  description: 'Modal description text',
  illustration: mockIllustration,
  onClose: mockOnClose,
  primaryButton: mockPrimaryButton,
  secondaryButton: mockSecondaryButton,
}

describe('ModalSimple', () => {
  it('should display correctly', () => {
    render(<ModalSimple {...defaultProps} />)

    expect(screen.getByLabelText('Fermer la fenêtre')).toBeOnTheScreen()
    expect(screen.getByText('Modal Title')).toBeOnTheScreen()
    expect(screen.getByText('Confirm')).toBeOnTheScreen()
  })

  describe('maxHeight calculation based on platform', () => {
    const originalPlatform = Platform.OS

    afterEach(() => {
      Platform.OS = originalPlatform
    })

    it('should calculate maxHeight by subtracting safe area insets on iOS', () => {
      Platform.OS = 'ios'

      render(<ModalSimple {...defaultProps} />)

      expect(screen.getByTestId('modalWrapper').props.style.maxHeight).toEqual(1302)
    })

    it('should use full window height for maxHeight on Android', () => {
      Platform.OS = 'android'

      render(<ModalSimple {...defaultProps} />)

      expect(screen.getByTestId('modalWrapper').props.style.maxHeight).toEqual(1334)
    })
  })
})
