import React from 'react'

import { remoteIllustrationUrls } from 'shared/illustrations/remoteIllustrations'
import { render, screen } from 'tests/utils'
import { RemoteIllustration, RemoteIllustrationProps } from 'ui/components/RemoteIllustration'
import { ModalSimpleContent } from 'ui/designSystem/ModalSimple/ModalSimpleContent'

jest.mock('ui/components/RemoteIllustration', () => ({
  RemoteIllustration: jest.fn(() => null),
}))

describe('ModalSimpleContent', () => {
  const defaultProps = {
    title: 'Test Title',
  }

  it('should render the title', () => {
    render(<ModalSimpleContent {...defaultProps} />)

    expect(screen.getByText('Test Title')).toBeOnTheScreen()
  })

  it('should render the description when provided', () => {
    render(<ModalSimpleContent {...defaultProps} description="Test description text" />)

    expect(screen.getByText('Test description text')).toBeOnTheScreen()
  })

  it('should render the illustration with size "s" when provided', () => {
    const mockIllustration: RemoteIllustrationProps = {
      backgroundColor: 'positive02',
      url: remoteIllustrationUrls.validStampMosaïcLarge,
    }

    render(<ModalSimpleContent {...defaultProps} illustration={mockIllustration} />)

    expect(RemoteIllustration).toHaveBeenCalledWith(
      expect.objectContaining({
        ...mockIllustration,
        size: 's',
      }),
      undefined
    )
  })
})
