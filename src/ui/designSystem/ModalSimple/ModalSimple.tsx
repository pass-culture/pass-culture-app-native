import React, { FunctionComponent } from 'react'
import { Platform, useWindowDimensions } from 'react-native'
import { useSafeAreaInsets } from 'react-native-safe-area-context'
import styled from 'styled-components/native'

import { ModalSimpleContent } from 'ui/designSystem/ModalSimple/ModalSimpleContent'
import { ModalSimpleFooter } from 'ui/designSystem/ModalSimple/ModalSimpleFooter'
import { ModalSimpleHeader } from 'ui/designSystem/ModalSimple/ModalSimpleHeader'
import { ModalSimpleProps } from 'ui/designSystem/ModalSimple/types'

export const ModalSimple: FunctionComponent<ModalSimpleProps> = ({
  title,
  illustration,
  description,
  onClose,
  primaryButton,
  secondaryButton,
  tertiaryButton,
}) => {
  const { top, bottom } = useSafeAreaInsets()
  const { height } = useWindowDimensions()

  // On iOS, height returns the total screen height (including the status bar and home indicator).
  // We subtract the safe area insets so the modal does not extend beyond the actually visible area.
  const iOSHeight = height - top - bottom
  const maxHeight = Platform.OS === 'android' ? height : iOSHeight

  return (
    <ModalWrapper maxHeight={maxHeight} testID="modalWrapper">
      <ModalSimpleHeader onClose={onClose} />

      <StyledScrollView bounces={false} showsVerticalScrollIndicator={false} nestedScrollEnabled>
        <ModalSimpleContent title={title} description={description} illustration={illustration} />
      </StyledScrollView>

      <ModalSimpleFooter
        primaryButton={primaryButton}
        secondaryButton={secondaryButton}
        tertiaryButton={tertiaryButton}
      />
    </ModalWrapper>
  )
}

const ModalWrapper = styled.View<{ maxHeight?: number }>(({ maxHeight }) => ({
  maxHeight,
  width: '100%',
  overflow: 'hidden',
}))

const StyledScrollView = styled.ScrollView({
  flexShrink: 1,
})
